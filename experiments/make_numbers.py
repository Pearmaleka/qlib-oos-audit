"""Write every number the paper quotes as LaTeX macros and tables.

Reads ``results/*.json``; writes ``paper/numbers.tex`` and ``paper/tables/*.tex``.
The paper never types a result by hand.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
PAPER = ROOT / "paper"

ORDER = ["linear", "lightgbm", "xgboost", "catboost", "doubleensemble", "mlp", "gru", "lstm", "alstm", "transformer"]
NAME = {
    "linear": "Linear",
    "lightgbm": "LightGBM",
    "xgboost": "XGBoost",
    "catboost": "CatBoost",
    "doubleensemble": "DoubleEnsemble",
    "mlp": "MLP",
    "gru": "GRU",
    "lstm": "LSTM",
    "alstm": "ALSTM",
    "transformer": "Transformer",
}


def macro_name(*parts: str) -> str:
    s = "".join(p[:1].upper() + p[1:] for p in parts)
    s = re.sub(r"[^A-Za-z]", "", s)
    return s


class Numbers:
    def __init__(self) -> None:
        self.lines: list[str] = []

    def add(self, name: str, value: str) -> None:
        self.lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    def write(self, path: Path) -> None:
        path.write_text("% Generated by experiments/make_numbers.py. Do not edit.\n" + "\n".join(self.lines) + "\n")


def f3(x: float) -> str:
    return f"{x:.3f}"


def f4(x: float) -> str:
    return f"{x:.4f}"


def pct(x: float, digits: int = 0) -> str:
    return f"{x:.{digits}f}\\%"


def ordered(d: dict) -> list[str]:
    return [m for m in ORDER if m in d]


def main() -> None:
    ic = json.loads((RES / "ic_audit.json").read_text())
    bt = json.loads((RES / "backtest_audit.json").read_text()) if (RES / "backtest_audit.json").exists() else {}
    fe = json.loads((RES / "feature_audit.json").read_text())
    n = Numbers()

    rep = ic["reproduction"]["models"]
    dec = ic["decay"]["models"]
    st = ic["staleness"]
    tests = ic["tests"]
    runs = ic["runs"]

    # ---- counts
    n.add("NModels", str(len(rep)))
    n.add("NRunsPub", str(sum(runs["pub"].values())))
    n.add("NRunsAll", str(sum(sum(v.values()) for v in runs.values())))
    gaps = [abs(rep[m]["ours_rank_ic"] - rep[m]["pub_rank_ic"]) for m in rep if "pub_rank_ic" in rep[m]]
    n.add("ReproMaxGap", f4(max(gaps)))
    n.add("ReproMeanGap", f4(float(np.mean(gaps))))
    tau = ic["reproduction"]["kendall_published_vs_ours"]["rank_ic"]
    n.add("ReproTau", f"{tau['tau']:.2f}")
    n.add("ReproTauP", f3(tau["p"]))

    # ---- decay
    n.add("MeanRankICPub", f4(ic["decay"]["mean_published"]))
    n.add("MeanRankICPost", f4(ic["decay"]["mean_post"]))
    n.add("MeanDecayPct", pct(-ic["decay"]["mean_change_pct"]))
    ch = {m: -dec[m]["change_pct"] for m in dec}
    n.add("MinDecayPct", pct(min(ch.values())))
    n.add("MaxDecayPct", pct(max(ch.values())))
    n.add("MinDecayModel", NAME[min(ch, key=ch.get)])
    n.add("MaxDecayModel", NAME[max(ch, key=ch.get)])
    tmin = min(dec[m]["post_t"] for m in dec)
    n.add("MinPostT", f"{tmin:.1f}")
    best_pub = max(dec, key=lambda m: dec[m]["published"])
    best_post = max(dec, key=lambda m: dec[m]["post"])
    n.add("BestPubModel", NAME[best_pub])
    n.add("BestPostModel", NAME[best_post])
    for m in dec:
        k = macro_name(NAME[m])
        n.add(f"Pub{k}", f4(dec[m]["published"]))
        n.add(f"Post{k}", f4(dec[m]["post"]))
        n.add(f"Decay{k}", pct(-dec[m]["change_pct"]))
        if m in rep and "pub_rank_ic" in rep[m]:
            n.add(f"Table{k}", f4(rep[m]["pub_rank_ic"]))

    # ---- staleness (2023-2026)
    refits = {m: st[m]["refit"] for m in st if "refit" in st[m]}
    if refits:
        best = max(refits, key=refits.get)
        n.add("BestRecentModel", NAME[best])
        n.add("BestRecentRankIC", f4(refits[best]))
    for m in st:
        k = macro_name(NAME[m])
        for proto in ("pub", "refit", "roll"):
            if proto in st[m]:
                n.add(f"Recent{macro_name(proto)}{k}", f4(st[m][proto]))
        if "refit_minus_pub" in st[m]:
            n.add(f"RefitGainP{k}", f3(st[m]["refit_minus_pub"]["p"]))

    # ---- statistical tests
    for key, tag in [("pub/published", "Pub"), ("pub/post", "Post"), ("refit/recent", "Recent")]:
        if key not in tests:
            continue
        t = tests[key]
        n.add(f"Days{tag}", str(t["days"]))
        n.add(f"MCSSize{tag}", str(len(t["mcs_included"])))
        n.add(f"MCSOf{tag}", str(len(t["mcs_pvalues"])))
        n.add(f"MCSList{tag}", ", ".join(NAME[m] for m in ordered(t["mcs_included"])))
        n.add(f"Pairs{tag}", str(t["pairs"]))
        n.add(f"PairsSig{tag}", str(t["pairs_p05"]))
        n.add(f"PairsHolm{tag}", str(t["pairs_holm"]))
        se = list(t["hac_se"].values())
        n.add(f"MedianSE{tag}", f4(float(np.median(se))))
        for b in ("lightgbm", "linear"):
            if f"spa_vs_{b}" in t:
                n.add(f"SPA{macro_name(b)}{tag}", f"{t[f'spa_vs_{b}']['consistent']:.2f}")
    for key, tag in [("pub/published", "Pub"), ("pub/post", "Post"), ("refit/recent", "Recent")]:
        s = ic["seed_noise"].get(key)
        if s:
            n.add(f"ICC{tag}", f"{s['icc']:.2f}")
            n.add(f"SeedSD{tag}", f4(float(np.sqrt(s["var_seed"]))))
            n.add(f"ModelSD{tag}", f4(float(np.sqrt(s["var_model"]))))
    rs = ic["rank_stability"]
    for k, tag in [
        ("ours_published_vs_ours_post", "PubPost"),
        ("published_table_vs_ours_post", "TablePost"),
        ("ours_published_vs_refit_recent", "PubRecent"),
        ("published_table_vs_refit_recent", "TableRecent"),
    ]:
        if k in rs:
            n.add(f"Tau{tag}", f"{rs[k]['tau']:.2f}")
            n.add(f"TauP{tag}", f"{rs[k]['p']:.2f}")

    # ---- features
    sm = fe["strong_mean_aligned"]
    n.add("FeatN", str(fe["n_features"]))
    n.add("FeatStrong", str(fe["n_strong"]))
    n.add("FeatTrain", f4(sm["train"]))
    n.add("FeatPub", f4(sm["published"]))
    n.add("FeatPost", f4(sm["post"]))
    n.add("FeatDropTrainPub", pct(100 * (1 - sm["published"] / sm["train"])))
    n.add("FeatDropPubPost", pct(100 * (1 - sm["post"] / sm["published"])))
    n.add("FeatSlope", f"{fe['slope_post_on_published']:.2f}")
    n.add("FeatFlips", str(fe["sign_flips_post"]))
    n.add("FeatMedianRatio", f"{fe['strong_median_ratio_post_over_published']:.2f}")

    # ---- portfolios
    if bt:
        ens = bt["ensembles"]
        for m, per in ens.get("pub", {}).items():
            k = macro_name(NAME.get(m, m))
            for period, tag in [("published", "Pub"), ("post", "Post")]:
                if period in per:
                    n.add(f"Ret{tag}{k}", pct(100 * per[period]["annual_excess"], 1))
                    n.add(f"IR{tag}{k}", f"{per[period]['information_ratio']:.2f}")
        for m, per in ens.get("refit", {}).items():
            if "recent" in per:
                k = macro_name(NAME.get(m, m))
                n.add(f"RetRecent{k}", pct(100 * per["recent"]["annual_excess"], 1))
                n.add(f"IRRecent{k}", f"{per['recent']['information_ratio']:.2f}")
        pubs = [per["published"]["annual_excess"] for per in ens.get("pub", {}).values() if "published" in per]
        posts = [per["post"]["annual_excess"] for per in ens.get("pub", {}).values() if "post" in per]
        if pubs and posts:
            n.add("MeanRetPub", pct(100 * float(np.mean(pubs)), 1))
            n.add("MeanRetPost", pct(100 * float(np.mean(posts)), 1))
        for period, tag in [("published", "Pub"), ("post", "Post"), ("recent", "Recent")]:
            x = bt.get("null", {}).get(period)
            if x:
                n.add(f"NullRet{tag}", pct(100 * x["annual_excess"], 1))
                n.add(f"NullRetSD{tag}", pct(100 * x["annual_excess_sd"], 1))
                n.add(f"NullIR{tag}", f"{x['information_ratio']:.2f}")
        if pubs and posts and "published" in bt.get("null", {}) and "post" in bt.get("null", {}):
            above_pub = float(np.mean(pubs)) - bt["null"]["published"]["annual_excess"]
            above_post = float(np.mean(posts)) - bt["null"]["post"]["annual_excess"]
            n.add("AboveNullPub", pct(100 * above_pub, 1))
            n.add("AboveNullPost", pct(100 * above_post, 1))
            n.add("AboveNullDrop", pct(100 * (1 - above_post / above_pub)))
        d = bt.get("deflated_sharpe_post", {})
        if d:
            best_model, best_tag = d["best"].split("/")
            n.add("DSRBest", f"{NAME.get(best_model, best_model)} (seed {best_tag.replace('seed', '')})")
            n.add("DSRTrials", str(d["trials"]))
            n.add("DSRIR", f"{d['information_ratio']:.2f}")
            n.add("DSRValue", f"{d['dsr']:.2f}")
            n.add("DSRPSR", f"{d['psr0']:.3f}")
            n.add("DSRSRZero", f"{d['sr0_annualised']:.2f}")

    n.write(PAPER / "numbers.tex")
    write_tables(ic, bt)


def write_tables(ic: dict, bt: dict) -> None:
    tdir = PAPER / "tables"
    tdir.mkdir(parents=True, exist_ok=True)
    rep = ic["reproduction"]["models"]
    dec = ic["decay"]["models"]
    st = ic["staleness"]
    brep = bt.get("reproduction", {}) if bt else {}

    # Table 1: reproduction in the published window.
    rows = []
    for m in ordered(rep):
        r = rep[m]
        b = brep.get(m, {})
        sd = f"\\,$\\pm$\\,{r['ours_rank_ic_sd']:.4f}" if r["seeds"] > 1 else ""
        ret_pub = f"{100 * b['pub_annual_excess']:.1f}" if "pub_annual_excess" in b else "--"
        ret_ours = f"{100 * b['ours_annual_excess']:.1f}" if "ours_annual_excess" in b else "--"
        ir_pub = f"{b['pub_information_ratio']:.2f}" if "pub_information_ratio" in b else "--"
        ir_ours = f"{b['ours_information_ratio']:.2f}" if "ours_information_ratio" in b else "--"
        rows.append(
            f"{NAME[m]} & {r['seeds']} & {r.get('pub_ic', float('nan')):.4f} & {r['ours_ic']:.4f} & "
            f"{r.get('pub_rank_ic', float('nan')):.4f} & {r['ours_rank_ic']:.4f}{sd} & "
            f"{ret_pub} & {ret_ours} & {ir_pub} & {ir_ours} \\\\"
        )
    (tdir / "reproduction.tex").write_text("\n".join(rows) + "\n\\bottomrule\n")

    # Table 2: decay and refits.
    rows = []
    for m in ordered(dec):
        d = dec[m]
        s = st.get(m, {})
        refit = f"{s['refit']:.4f}" if "refit" in s else "--"
        roll = f"{s['roll']:.4f}" if "roll" in s else "--"
        stale = f"{s['pub']:.4f}" if "pub" in s else "--"
        rows.append(
            f"{NAME[m]} & {d['published']:.4f} & {d['post']:.4f} & {d['change_pct']:+.0f}\\% & {d['post_t']:.1f} & "
            f"{stale} & {refit} & {roll} \\\\"
        )
    (tdir / "decay.tex").write_text("\n".join(rows) + "\n\\bottomrule\n")

    # Table 3: tests per window.
    rows = []
    labels = {"pub/published": "2017--07/2020", "pub/post": "08/2020--11/2026", "refit/recent": "2023--2026 (refit)"}
    for key, label in labels.items():
        t = ic["tests"].get(key)
        if not t:
            continue
        s = ic["seed_noise"].get(key, {})
        spa_l = t.get("spa_vs_lightgbm", {}).get("consistent", float("nan"))
        spa_o = t.get("spa_vs_linear", {}).get("consistent", float("nan"))
        icc = f"{s['icc']:.2f}" if s else "--"
        rows.append(
            f"{label} & {t['days']} & {len(t['mcs_included'])}/{len(t['mcs_pvalues'])} & "
            f"{t['pairs_p05']}/{t['pairs']} & {t['pairs_holm']} & {spa_l:.2f} & {spa_o:.2f} & {icc} \\\\"
        )
    (tdir / "tests.tex").write_text("\n".join(rows) + "\n\\bottomrule\n")

    # Table 4: portfolios.
    if bt:
        ens = bt["ensembles"]
        rows = []
        for m in ordered(ens.get("pub", {})):
            p = ens["pub"][m]
            r = ens.get("refit", {}).get(m, {}).get("recent")

            def cell(x):
                return f"{100 * x['annual_excess']:.1f} & {x['information_ratio']:.2f}" if x else "-- & --"

            rows.append(f"{NAME[m]} & {cell(p.get('published'))} & {cell(p.get('post'))} & {cell(r)} \\\\")
        null = bt.get("null", {})
        if null:

            def ncell(x):
                return f"{100 * x['annual_excess']:.1f} & {x['information_ratio']:.2f}" if x else "-- & --"

            rows.append("\\midrule")
            rows.append(
                f"Random scores ({null['post']['seeds']} seeds) & {ncell(null.get('published'))} & "
                f"{ncell(null.get('post'))} & {ncell(null.get('recent'))} \\\\"
            )
        (tdir / "portfolio.tex").write_text("\n".join(rows) + "\n\\bottomrule\n")


if __name__ == "__main__":
    main()
